"""
Write reports/diagnostic_implementation/EXPERIMENT_RECORD.md from the experiment output folders (nothing is re-run).

    <python> -B dev_tools/experiment_record.py

Reads, for v1 (experiments/) and v2 (experiments_v2_rules11_run2/): manifest.json, results.json,
results_by_condition.csv, a_vs_b.json, decision.json. Every number in the record comes from those files.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "reports" / "diagnostic_implementation"
RUNS = {"v1 (rules-1.0)": D / "experiments", "v2 (rules-1.1)": D / "experiments_v2_rules11_run2"}
OPT = ["baseline", "rule_removal", "rule_removal+crop_fill", "contrast_clahe", "wider_margin_0.4h"]


def load(folder):
    tab = list(csv.DictReader(open(folder / "results_by_condition.csv", encoding="utf-8")))
    return {"manifest": json.loads((folder / "manifest.json").read_text(encoding="utf-8")), "results": json.loads((folder / "results.json").read_text(encoding="utf-8")),
            "table": tab, "ab": json.loads((folder / "a_vs_b.json").read_text(encoding="utf-8")), "decision": json.loads((folder / "decision.json").read_text(encoding="utf-8"))}


def pct(x):
    return "—" if x in ("", None, "None") else f"{100 * float(x):.1f}"


out = ["# Experiment record — segmentation variants on synthetic pages", "",
       "Generated by `dev_tools/experiment_record.py` from the result files; nothing here is typed by hand.", "",
       "Pages: `dev_tools/synthetic_conditions.py` (12 conditions), 3 pages per condition per split, rendered with the project's fonts "
       "and a fixed list of common Tamil words; labels (text and word boxes) come from the generator. Recognizer: registered Experiment 002-A "
       "checkpoint, production functions (`wordocr.fullpage`). Variants run on identical PNG bytes.", ""]
for name, folder in RUNS.items():
    if not (folder / "results.json").is_file():
        out += [f"## {name}", "", f"`{folder.relative_to(ROOT).as_posix()}` has no results.json: run incomplete.", ""]
        continue
    r = load(folder)
    m = r["manifest"]
    splits = sorted({p["split"] for p in m["pages"]})
    seeds = {s: sorted({p["seed"] for p in m["pages"] if p["split"] == s}) for s in splits}
    ck = sorted({x.get("checkpoint_sha256") for x in r["results"] if x.get("checkpoint_sha256")})
    errs = [x for x in r["results"] if "error" in x]
    out += [f"## {name} — `{folder.relative_to(ROOT).as_posix()}`", "",
            f"- Pages: {len(m['pages'])} ({', '.join(f'{s}: {len(seeds[s])} pages, seeds {seeds[s][0]}–{seeds[s][-1]}' for s in splits)}); "
            f"labelled words: {sum(p['words'] for p in m['pages'])}.",
            f"- Duplicate images within or across splits: {len(m['duplicate_images'])} / {len(m['duplicates_across_splits'])}.",
            f"- Page runs: {len(r['results'])}; runs that raised an error: {len(errs)}; checkpoint SHA-256 seen: {', '.join(c[:16] + '…' for c in ck)}.", "",
            "### Per condition and variant", "",
            "Matched = labelled words found as one region (IoU ≥ 0.5). CER = page character error rate on the exact text (spaces and line breaks kept); "
            "CER-nws = CER after removing all whitespace. Words correct = among matched regions.", "",
            "| Split | Condition | Variant | Words | Matched % | Split | Merged | Missed | CER % | CER-nws % | Words correct % |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in r["table"]:
        out.append(f"| {t['split']} | {t['condition']} | {t['variant']} | {t['truth_words']} | {pct(t['matched_rate'])} | {t['split_words']} | {t['merged']} | {t['missed']} | "
                   f"{pct(t['page_CER'])} | {pct(t['page_CER_no_whitespace'])} | {pct(t['matched_words_correct_rate'])} |")
    out += ["", "### Condition A (labelled box cut from the page) versus B (pipeline crop), baseline segmentation, same recognizer", "",
            "| Split / condition | Words | A correct | B correct | A CER % | B CER % | B re-read = page result |", "|---|---|---|---|---|---|---|"]
    for k, v in r["ab"].items():
        out.append(f"| {k} | {v['words']} | {v['A_manual_correct']} | {v['B_pipeline_correct']} | {pct(v['A_CER'])} | {pct(v['B_CER'])} | {v['pipeline_reread_consistent']} |")
    totA = sum(v["A_manual_correct"] for v in r["ab"].values()); totN = sum(v["words"] for v in r["ab"].values())
    out += ["", f"Condition A total: {totA} of {totN} words correct.", "", "### Per-page results on ruled conditions", "",
            "| Split | Condition | Seed | Variant | Words | Regions | Matched | Missed | CER % | Flags |", "|---|---|---|---|---|---|---|---|---|---|"]
    for x in r["results"]:
        if x["condition"].startswith("ruled") and x["variant"] in ("baseline", "rule_removal", "rule_removal+crop_fill"):
            out.append(f"| {x['split']} | {x['condition']} | {x['seed']} | {x['variant']} | {x.get('truth_words')} | {x.get('pred_regions')} | {x.get('matched')} | "
                       f"{x.get('missed')} | {pct(x['char_errors'] / x['ref_chars']) if x.get('ref_chars') else '—'} | {'; '.join(x.get('flags', []))[:120]} |")
    worst = sorted((x for x in r["results"] if x["variant"] == "rule_removal" and x.get("ref_chars")), key=lambda x: -x["char_errors"] / x["ref_chars"])[:5]
    out += ["", "Worst five pages with `rule_removal` (any condition): " + "; ".join(f"{x['split']}/{x['condition']}/{x['seed']} CER {pct(x['char_errors'] / x['ref_chars'])} %" for x in worst), "",
            "### Decision (rule fixed before the run: a candidate must lower page CER on a target condition by ≥ 1 point on development, "
            "with no other condition worse by > 0.5 point CER or > 1 point matched rate, and the same on held-out)", ""]
    for v, d in r["decision"].items():
        out.append(f"- **{v}: {d['verdict']}**. Development: gains {d['development']['gains_on_targets']}, regressions {d['development']['regressions']}. "
                   f"Held-out: gains {d['heldout']['gains_on_targets']}, regressions {d['heldout']['regressions']}.")
    out.append("")
out += ["## What these runs can and cannot show", "",
        "- They measure the segmentation under controlled synthetic damage, and separate segmentation failures from recognition failures (A vs B).",
        "- The recognizer part is not independent of training: same fonts and generator family; the word list overlaps common vocabulary.",
        "- `handwriting_style_font` is a printed font. No real handwriting and no real document was evaluated.",
        "- The v1 held-out split (seeds 5000+) was inspected after the v1 run; rules-1.1 was therefore confirmed on a new held-out split (seeds 9000+) in v2.", ""]
(D / "EXPERIMENT_RECORD.md").write_text("\n".join(out), encoding="utf-8")
print(f"written: {len(out)} lines")
